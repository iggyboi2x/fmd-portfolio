// Regenerates src/components/techIconPaths.js from simple-icons (CC0) with only
// the SVG path of each logo the site uses, so the brand metadata (titles,
// source URLs, guidelines) never ships to the browser.
//
//   node scripts/gen-tech-icons.mjs
//
// To add a logo: add its simple-icons export name below, rerun, then map the
// skill label to it in TechIcon.jsx.
import { writeFileSync } from 'node:fs'
import * as si from 'simple-icons'

const ICONS = [
  'siClaude', 'siExpress', 'siFigma', 'siGithub', 'siLaravel', 'siLivekit', 'siNextdotjs', 'siNodedotjs',
  'siPhp', 'siReact', 'siSupabase', 'siTailwindcss', 'siTypescript', 'siVercel', 'siVite',
]

const lines = ICONS.map(name => {
  if (!si[name]) throw new Error(`simple-icons has no ${name}`)
  return `export const ${name} = ${JSON.stringify(si[name].path)} // ${si[name].title}`
})

writeFileSync(
  new URL('../src/components/techIconPaths.js', import.meta.url),
  `// Generated by scripts/gen-tech-icons.mjs from simple-icons (CC0-1.0). Do not edit by hand.\n${lines.join('\n')}\n`,
)
console.log(`wrote ${ICONS.length} icon paths`)
